# Circumference of a circle = 2 * pi * r

import math

radius = float(input("Please enter radius value of circle: "))

circumference = 2 * math.pi * radius

# print(f"The circumference of the circle is: {circumference}")
print(f"The circumference of the circle is: {round(circumference, 3)}cms") # rounds off the decimal place to 3 digits 